package io.github.nihaoljx.flowchart.llm;

/**
 * LLM 候选失败的性质分类。
 *
 * 为什么要有这一层：冷却时长应该由"错误的性质"决定，而不是由
 * HTTP 状态码决定。同一个状态码下，"重试有没有用"可以完全不同 ——
 * 401 重试一万次还是 401（额度/鉴权），而 5xx 下一轮可能就好了。
 * 只按状态码散在 if-else 里判，必然会把"这次请求本身有问题"错当成
 * "这个候选有问题"，从而误冷却一个健康的候选。
 *
 * 分类只在这一处判定，冷却时长再由 `FailoverLlmProvider` 按分类查表 ——
 * 这样"哪类错误会导致长期摘除候选"一眼可查，不会被散落的魔法数字掩盖。
 */
public enum LlmFailureKind {

    /**
     * 确定性失败：请求本身的问题（上下文超长、参数非法）。
     *
 * 关键区别：换成任何一个候选都会得到同样的错，因为错在请求上。
     * 所以处置铁律是"不冷却候选"—— 误冷却等同于凭空摘掉一个健康候选。
     *
 * 是否顺带中断整条候选链，取决于这个错是否与候选无关：
     * 上下文超长与候选无关，中断；而"某家不支持某个参数"这类 4xx
     * 是厂商特性差异，换家可能通，所以继续往下试。
     */
    DETERMINISTIC,

    /** 瞬时失败：5xx / 超时 / 网络抖动。换个候选或下一轮大概率自愈。 */
    TRANSIENT,

    /** 额度与限流：候选本身没坏，是没配额或被打满，需要等或切家。 */
    QUOTA,

    /** 永久失败：模型下线 / 无权限 / id 不存在。只能等人工介入。 */
    PERMANENT
}
