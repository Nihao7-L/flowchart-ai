package io.github.nihaoljx.flowchart.service;

/**
 * 生成流程的时间预算（唯一的预算真相源）
 *
 * 职责只有一件事：说清"一次生成总共能花多久"。
 * 谁需要跟预算对齐（SSE 通道上限、agent run 截止时刻）都从这里读，
 * 不允许各处自设数字 —— 否则就会出现"生成还没跑完、通道先被掐断"。
 *
 * 轮次/单步超时不在这里：agent 循环按剩余预算自行折算
 * （AgentLoop.remainingSeconds），没有固定轮次概念。
 */
public final class GenerationBudget {

    /**
     * 单次生成的总时间预算（毫秒）
     *
     * SSE 通道上限由 DiagramController 取"本值 + 收尾余量"推导，
     * 两者因此恒等对齐。把 120 秒硬编码在控制器里、与本预算无关，
     * 而实测单轮 LLM 调用就要约 100 秒——慢图必然撞墙，现象是
     * 流被容器掐断、前端颗粒无收。
     *
     * 2026-10-16 用户拍板：单图 SLA = 100 秒，超时即判失败。
     * 现值 120 秒 = SLA + 20 秒故障转移余量。为什么要留余量：
     * 候选失败有两类 —— 一来就失败的（402/403/空 choices，毫秒级，
     * 剩下的时间够试下一家）与挂死的（吃满单次调用硬帽）。前者
     * 有这 20 秒就能继续往下切候选，后者则确实该判失败。
     *
     * 旧值 3600 秒（1 小时）是在"模型自己算坐标、单次调用数分钟"
     * 的前提下定的；那条路已被语义路径（submit_spec）取代，1 小时
     * 的窗口就从"必要的耐心"变成了"允许一张图悄悄跑一小时"，
     * 实测正是它让挂死候选烧穿了整夜。
     *
     * ⚠️ 2026-10-16 深夜修正：上述"单图 ≤100s"的 SLA 前提是模型走
     * submit_spec（5~30s 收敛）；但复杂图（8 参与者时序图实测 184s）
     * 会让模型自选 submit_scene 老路、合法地慢，被 120s 预算 + 140s
     * SSE 联手掐断（后端其实已生成成功，却送达失败）。真正要防的
     * "挂死烧一夜"已由客户端**流式空闲判死**兜住（OpenAiToolClient：
     * 连续 idleTimeoutSeconds 秒无新分片就切，默认 120s）—— 挂死候选
     * 到点就死、不会烧到预算上限。故本预算抬到 1000s（= 用户要的
     * "1000 上限"）：慢图能跑完并送达，绝对天花板防"流式永不停"的
     * 极端情况。SSE 通道随之到 1020s（DiagramController 联动）。
     */
    public static final long TOTAL_BUDGET_MS = 1_000_000L;

    private GenerationBudget() {
    }

    /**
     * 总预算的运行时读数。
     *
     * 为什么需要它：TOTAL_BUDGET_MS 是 static final 字面量，
     * 别的类若写 `GenerationBudget.TOTAL_BUDGET_MS + 20_000L` 就是一个
     * **编译期常量表达式**，javac 会把它内联进调用方的 class 文件，
     * 运行时不再回读本类 —— "只改本文件、调用方源码没动"时增量编译
     * 不重编译调用方，两边的值静默失配（曾导致 SSE 通道先于生成结束被
     * 掐断）。方法调用不是编译期常量，调用方永远读到当前值。
     * 需要与本值恒等对齐的地方一律调本方法，不要直接引用常量。
     */
    public static long totalBudgetMs() {
        return TOTAL_BUDGET_MS;
    }
}
